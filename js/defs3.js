// Бытовая электрика: розетка, приборы с вилкой, блок питания, микроволновка, трёхфазный выпрямитель, осциллограф, авария (КЗ)
import { fmt, cabs } from './sim.js';
import { DEFS, tt, U, I, P } from './defs.js';

// потребляемая мощность, кратность пускового тока, длительность пуска
export const KINDS = { 'чайник 2 кВт': [2000, 1, 0], 'обогреватель 1,5 кВт': [1500, 1, 0], 'стиральная машина 2,2 кВт': [2200, 3, 0.5], 'холодильник 150 Вт': [150, 8, 0.4], 'компрессор 1,5 кВт': [1500, 14, 0.3] };
const FAULT = P('Неисправность', ['нет', 'пробой на корпус', 'утечка 50 мА'], 'нет');

function appliance(mw) {
  return {
    name: mw ? 'Микроволновая печь' : 'Бытовой прибор', mark: mw ? 'MW' : 'A', cat: 'Нагрузка', w: mw ? 14 : 12, h: 13, d: 8, art: mw ? 'rect' : 'sockets',
    terms: [...tt(['L', 'N', 'PE'], [-3, 0, 3], 13, 1), ...tt(['корпус'], [0], 13, -1)],
    params: mw ? { Pn: P('Мощность СВЧ', [700, 900, 1200], 900, 'Вт'), fault: FAULT } : { kind: P('Прибор', Object.keys(KINDS), 'чайник 2 кВт'), fault: FAULT },
    init: () => ({ on: true, t: 0, u: 0, i: 0, burned: false, uc: 0, k: 1 }),
    spec: c => mw ? [c.p.Pn * 1.5, 3, 0.3] : KINDS[c.p.kind],
    stamp(c, net, T) {
      const [Pw, k, dur] = this.spec(c), s = c.state; net.R(T('корпус'), T('PE'), 0.01);            // металлический корпус соединён с заземляющим контактом вилки
      s.k = s.t < dur ? k : 1; const z = 230 * 230 / Pw / s.k;
      c._e = s.on && !s.burned ? (k > 1 ? net.R(T('L'), T('N'), z * 0.85, z * 0.5) : net.R(T('L'), T('N'), z)) : null;
      if (c.p.fault === 'пробой на корпус') net.R(T('L'), T('корпус'), 1); else if (c.p.fault === 'утечка 50 мА') net.R(T('L'), T('корпус'), 4600);
    },
    step(c, net, dt, emit, T) {
      const s = c.state; s.u = U(net, T, 'L', 'N'); s.i = I(c._e); s.uc = cabs(net.v(T('корпус')));
      if (s.u > 100 && s.on) s.t += dt; else if (s.u < 60 || !s.on) s.t = 0;
      if (!s.burned && s.u > 300) { s.burned = true; emit('bad', `💥 ${c.label}: прибор на 230 В получил ${fmt(s.u)}В и сгорел (обрыв нуля? включён между фазами?)`, 'burn'); }
    },
    click(c) { if (c.state.burned) c.state.burned = false; else c.state.on = !c.state.on; },
    read(c) {
      const s = c.state, run = s.on && s.u > 100 && !s.burned;
      return [['Питание L–N', fmt(s.u) + 'В'], ['Ток', fmt(s.i) + 'А'], ['Режим', s.burned ? 'СГОРЕЛ (клик — заменить)' : !s.on ? 'выключен (клик)' : !run ? 'нет питания' : s.k > 1 ? `ПУСК: ток ×${s.k}` : 'работает'],
      ['Напряжение на корпусе', fmt(s.uc) + 'В' + (s.uc > 50 ? ' ⚠ ОПАСНО' : '')], ...(mw && run ? [['Вторичная обмотка', '≈ 2100 В ~'], ['На магнетроне (после удвоителя)', '≈ 4000 В =']] : [])];
    },
    how: mw ? 'Внутри — высоковольтный трансформатор (230 → 2100 В), конденсатор и диод, которые вместе <b>удваивают и выпрямляют</b> напряжение до ≈ 4000 В постоянного тока для магнетрона. Магнетрон превращает его в СВЧ-излучение 2,45 ГГц. Клик — включить/выключить. Конденсатор хранит заряд и после отключения — вскрывать опасно.'
      : 'Прибор с вилкой: L, N и заземляющий контакт PE, который внутри соединён с металлическим <b>корпусом</b>. К выводу «корпус» можно подключить человека и посмотреть, что будет при неисправности с заземлением и без него. У приборов с двигателем есть пусковой ток. Клик — включить/выключить.'
  };
}

