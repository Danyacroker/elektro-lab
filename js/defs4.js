// Соединительные элементы щита: проходная клемма и шина N / PE
import { fmt } from './sim.js';
import { DEFS, tt, I, P } from './defs.js';

Object.assign(DEFS, {
  xt: {
    name: 'Клемма проходная', mark: 'XT', cat: 'Коммутация', w: 3, h: 7, d: 4, art: 'lugs',
    terms: [...tt(['1'], [0], 7, 1), ...tt(['2'], [0], 7, -1)], params: {},
    init: () => ({ i: 0 }),
    stamp(c, net, T) { c._e = net.R(T('1'), T('2'), 0.002); }, step(c) { c.state.i = I(c._e); },
    read: c => [['Ток через клемму', fmt(c.state.i) + 'А']],
    how: 'Клемма на DIN-рейку: два винтовых зажима на общей токоведущей пластине. Через клеммы провода щита соединяются с кабелями, уходящими наружу, — к двигателю, кнопочному посту, датчикам. К каждому зажиму можно подключить несколько проводов: это удобная точка разветвления.'
  },
  bus: {
    name: 'Шина N / PE', mark: 'X', cat: 'Коммутация', w: 14, h: 6, d: 3, art: 'net',
    terms: [...tt(['1', '2', '3'], [-4.5, 0, 4.5], 6, 1), ...tt(['4', '5', '6'], [-4.5, 0, 4.5], 6, -1)],
    params: { kind: P('Назначение', ['N — нулевая', 'PE — заземления'], 'N — нулевая') },
    init: () => ({ i: 0 }),
    stamp(c, net, T) { c._e = ['1', '2', '3', '4', '5'].map((a, k) => net.R(T(a), T(['2', '3', '4', '5', '6'][k]), 0.001)); },
    step(c) { c.state.i = Math.max(...c._e.map(I)); },
    read: c => [['Назначение', c.p.kind], ['Наибольший ток по шине', fmt(c.state.i) + 'А']],
    how: 'Латунная планка с рядом винтов. В щите все нулевые проводники сходятся на шине N (синяя), все защитные — на шине PE (жёлто-зелёная). Каждый провод — под свой винт: так любой можно отсоединить, не трогая остальные. Шины N и PE между собой не соединяют (кроме одной точки на вводе в системе TN-C-S).'
  },
});
// для режима «Чтение схем»: какие выводы «прозрачных» элементов считаются одной точкой
